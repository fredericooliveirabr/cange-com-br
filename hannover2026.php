            // ------------------------------------------
            // Countdown Timer (vanilla JS, no libraries)
            // April 20, 2026 00:00:00 CEST = UTC+2
            // ------------------------------------------
            function initCountdown() {
                var eventDate = new Date('2026-04-20T00:00:00+02:00');

                function pad(n) { return n < 10 ? '0' + n : String(n); }

                function tick() {
                    var diff = eventDate - Date.now();

                    if (diff <= 0) {
                        ['cd-days', 'cd-hours', 'cd-minutes', 'cd-seconds'].forEach(function (id) {
                            document.getElementById(id).textContent = '00';
                        });
                        var big = document.getElementById('hm26-days-big');
                        if (big) big.textContent = '0';
                        return;
                    }

                    var days = Math.floor(diff / 86400000);
                    var hours = Math.floor((diff % 86400000) / 3600000);
                    var minutes = Math.floor((diff % 3600000) / 60000);
                    var seconds = Math.floor((diff % 60000) / 1000);

                    document.getElementById('cd-days').textContent = pad(days);
                    document.getElementById('cd-hours').textContent = pad(hours);
                    document.getElementById('cd-minutes').textContent = pad(minutes);
                    document.getElementById('cd-seconds').textContent = pad(seconds);

                    var big = document.getElementById('hm26-days-big');
                    if (big) big.textContent = days;
                }

                tick();
                setInterval(tick, 1000);
            }

            // ------------------------------------------
            // Contact Form Submission (Formspree)
            // ------------------------------------------
            document.getElementById('contact-form').addEventListener('submit', function (e) {
                e.preventDefault();

                const form = e.target;
                const btn = form.querySelector('button[type="submit"]');
                const msgBox = document.getElementById('form-message');
                const isDE = document.documentElement.lang === 'de';

                const originalText = btn.textContent;
                btn.disabled = true;
                btn.textContent = '...';
                msgBox.textContent = '';

                fetch('https://formspree.io/f/xdawpdqz', {
                    method: 'POST',
                    body: new FormData(form),
                    headers: { 'Accept': 'application/json' }
                })
                    .then(function (response) {
                        if (response.ok) {
                            msgBox.style.color = 'green';
                            msgBox.textContent = isDE
                                ? 'Nachricht gesendet! Wir melden uns bald bei Ihnen.'
                                : 'Message sent! We will get back to you shortly.';
                            form.reset();
                        } else {
                            return response.json().then(function (data) {
                                throw new Error(data.errors ? data.errors.map(function (e) { return e.message; }).join(', ') : 'Server error');
                            });
                        }
                    })
                    .catch(function (err) {
                        msgBox.style.color = 'red';
                        msgBox.textContent = isDE
                            ? 'Fehler beim Senden. Bitte schreiben Sie direkt an: frederico.oliveira@cange.me'
